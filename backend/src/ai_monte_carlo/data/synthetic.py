"""Synthetic workload generation module for AI Monte Carlo Lab.

Produces reproducible synthetic request traces (input/output tokens, latencias, costos)
using NumPy random generators and pandas DataFrames.

Note:
    Data generated by this module is purely synthetic, derived from parametric distributions
    for benchmark and stress-testing purposes. It does not represent real-world empirical production
    logs unless calibrated with observational telemetry.
"""

from __future__ import annotations

from pathlib import Path
from typing import Sequence

import numpy as np
import pandas as pd

from ai_monte_carlo.config import (
    LatencyConfig,
    PricingConfig,
    TokenDistributionConfig,
)
from ai_monte_carlo.simulation.generators import sample_latency, sample_tokens


def generate_synthetic_requests(
    n_requests: int,
    token_in_config: TokenDistributionConfig | None = None,
    token_out_config: TokenDistributionConfig | None = None,
    latency_config: LatencyConfig | None = None,
    pricing_config: PricingConfig | None = None,
    start_timestamp: str | pd.Timestamp = "2026-01-01 00:00:00",
    mean_interval_seconds: float = 2.5,
    seed: int | None = 42,
) -> pd.DataFrame:
    """Generates a reproducible pandas DataFrame with synthetic LLM request records.

    Each row represents a simulated inference request with:
    - request_id: Unique synthetic identifier.
    - timestamp: Inter-arrival timestamps modeled via Exponential renewal process.
    - input_tokens: Number of prompt tokens drawn from token_in_config.
    - output_tokens: Number of completion tokens drawn from token_out_config.
    - total_tokens: Sum of input and output tokens.
    - latency_ms: Simulated response latency in milliseconds.
    - cost_input_usd: Direct input token cost.
    - cost_output_usd: Direct output token cost.
    - cost_total_usd: Total request inference cost in USD.

    Args:
        n_requests: Total number of requests to generate (>= 1).
        token_in_config: Parameters for input token distribution (default if None).
        token_out_config: Parameters for output token distribution (default if None).
        latency_config: Parameters for latency model (default if None).
        pricing_config: Pricing rates per 1M tokens (default if None).
        start_timestamp: Base timestamp for first request.
        mean_interval_seconds: Mean inter-arrival time in seconds (> 0).
        seed: Random seed for deterministic reproducibility.

    Returns:
        pd.DataFrame indexed from 0 to n_requests - 1 with calculated attributes.
    """
    if n_requests < 1:
        raise ValueError(f"n_requests must be at least 1, got {n_requests}")
    if mean_interval_seconds <= 0:
        raise ValueError(
            f"mean_interval_seconds must be strictly positive, got {mean_interval_seconds}"
        )

    t_in_cfg = token_in_config if token_in_config is not None else TokenDistributionConfig()
    t_out_cfg = token_out_config if token_out_config is not None else TokenDistributionConfig(
        mean=300.0, std=150.0
    )
    lat_cfg = latency_config if latency_config is not None else LatencyConfig()
    price_cfg = pricing_config if pricing_config is not None else PricingConfig()

    rng = np.random.default_rng(seed)

    # 1. Sample tokens
    input_tokens = sample_tokens(rng, t_in_cfg, size=n_requests)
    output_tokens = sample_tokens(rng, t_out_cfg, size=n_requests)
    total_tokens = input_tokens + output_tokens

    # 2. Sample latencies
    latencies = sample_latency(rng, input_tokens, output_tokens, lat_cfg)

    # 3. Simulate arrival timestamps (Poisson point process / Exponential inter-arrival)
    inter_arrivals_sec = rng.exponential(scale=mean_interval_seconds, size=n_requests)
    inter_arrivals_sec[0] = 0.0  # Start immediately at start_timestamp
    cumulative_seconds = np.cumsum(inter_arrivals_sec)

    base_time = pd.to_datetime(start_timestamp)
    timestamps = base_time + pd.to_timedelta(cumulative_seconds, unit="s")

    # 4. Compute costs
    cost_in = (input_tokens / 1_000_000.0) * price_cfg.cost_per_million_input
    cost_out = (output_tokens / 1_000_000.0) * price_cfg.cost_per_million_output
    cost_total = cost_in + cost_out

    # 5. Format request IDs with zero padding
    width = max(6, len(str(n_requests)))
    request_ids = [f"req_{i:0{width}d}" for i in range(1, n_requests + 1)]

    df = pd.DataFrame(
        {
            "request_id": request_ids,
            "timestamp": timestamps,
            "input_tokens": input_tokens,
            "output_tokens": output_tokens,
            "total_tokens": total_tokens,
            "latency_ms": latencies,
            "cost_input_usd": np.round(cost_in, 6),
            "cost_output_usd": np.round(cost_out, 6),
            "cost_total_usd": np.round(cost_total, 6),
        }
    )

    return df


def save_synthetic_requests(
    df: pd.DataFrame,
    filepath: str | Path,
) -> None:
    """Exports a synthetic requests DataFrame to CSV format.

    Args:
        df: DataFrame produced by generate_synthetic_requests.
        filepath: Target output file path.
    """
    path = Path(filepath)
    path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(path, index=False)
