"""Synthetic daily demand generation module for AI Monte Carlo Lab.

Produces reproducible daily time-series request counts with customizable trend,
weekly seasonality, calendar features, and discrete count stochasticity.

Note:
    Data generated by this module is purely synthetic, derived from parametric trend,
    seasonality, and stochastic count processes for statistical modeling and Monte Carlo simulation.
    It does not represent real-world empirical production traffic unless calibrated with observational telemetry.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import date
from typing import Sequence

import numpy as np
import pandas as pd


@dataclass(frozen=True)
class DailyDemandConfig:
    """Configuration for synthetic daily demand time-series generation.

    Attributes:
        n_days: Total number of days in the generated series (must be >= 1).
        start_date: Starting date in ISO format 'YYYY-MM-DD' (default: '2026-01-01').
        base_demand: Baseline expected requests per day on day 0 (must be >= 0).
        trend_slope: Average daily increase/decrease in requests per day.
        weekly_seasonality: Tuple of 7 non-negative multipliers for days Monday (0) to Sunday (6).
        noise_dispersion: Dispersion parameter for discrete noise (>= 0).
        noise_family: Distribution family for daily arrivals ('poisson', 'negative_binomial', 'fixed').
        seed: Random seed for deterministic reproducibility.
    """

    n_days: int = 180
    start_date: str = "2026-01-01"
    base_demand: float = 1_000.0
    trend_slope: float = 2.0
    weekly_seasonality: tuple[float, ...] = (1.05, 1.10, 1.12, 1.08, 0.95, 0.70, 0.60)
    noise_dispersion: float = 0.05
    noise_family: str = "poisson"
    seed: int | None = 42

    def __post_init__(self) -> None:
        if self.n_days < 1:
            raise ValueError(f"n_days must be at least 1, got {self.n_days}")
        if self.base_demand < 0:
            raise ValueError(f"base_demand must be non-negative, got {self.base_demand}")
        if len(self.weekly_seasonality) != 7:
            raise ValueError(
                f"weekly_seasonality must contain exactly 7 multipliers (Monday-Sunday), got {len(self.weekly_seasonality)}"
            )
        for idx, mult in enumerate(self.weekly_seasonality):
            if mult < 0:
                raise ValueError(
                    f"weekly_seasonality multipliers must be non-negative, got {mult} at index {idx}"
                )
        if self.noise_dispersion < 0:
            raise ValueError(f"noise_dispersion must be non-negative, got {self.noise_dispersion}")

        valid_noise_families = {"poisson", "negative_binomial", "fixed"}
        if self.noise_family not in valid_noise_families:
            raise ValueError(
                f"Unsupported noise_family: {self.noise_family}. Must be one of {valid_noise_families}"
            )
        if self.noise_family == "negative_binomial" and self.noise_dispersion <= 0:
            raise ValueError(
                f"noise_dispersion must be strictly positive for negative_binomial, got {self.noise_dispersion}"
            )

        # Validate that expected demand doesn't become strictly negative across the horizon
        min_trend = self.base_demand + self.trend_slope * (self.n_days - 1)
        if min_trend < 0:
            raise ValueError(
                f"trend_slope ({self.trend_slope}) causes negative expected demand ({min_trend:.2f}) "
                f"within {self.n_days} days from base {self.base_demand}."
            )


def generate_daily_demand(
    config: DailyDemandConfig | None = None,
) -> pd.DataFrame:
    """Generates a reproducible daily demand DataFrame with calendar features and request counts.

    The expected demand for day t (0-indexed) with day-of-week d is modeled as:
        mu(t) = max(0, (base_demand + trend_slope * t) * seasonality[d])

    Stochastic count realizations are drawn according to noise_family:
        - 'poisson': Y_t ~ Poisson(mu(t))
        - 'negative_binomial': Y_t ~ NegBinomial(mu(t), dispersion)
        - 'fixed': Y_t = round(mu(t))

    Args:
        config: DailyDemandConfig instance. Uses default settings if None.

    Returns:
        pd.DataFrame with columns:
        - date: pd.Timestamp of the date.
        - time_index: int (0 to n_days - 1).
        - day_of_week: int (0 = Monday, 6 = Sunday).
        - day_name: str (e.g. 'Monday', 'Tuesday').
        - is_weekend: int (1 if Saturday or Sunday, else 0).
        - requests: int (non-negative integer observed requests).
    """
    cfg = config if config is not None else DailyDemandConfig()
    rng = np.random.default_rng(cfg.seed)

    # 1. Temporal sequence
    dates = pd.date_range(start=cfg.start_date, periods=cfg.n_days, freq="D")
    time_indices = np.arange(cfg.n_days, dtype=np.int64)
    day_of_weeks = dates.dayofweek.to_numpy(dtype=np.int64)
    day_names = dates.day_name().to_numpy()
    is_weekends = (day_of_weeks >= 5).astype(np.int64)

    # 2. Deterministic expected demand
    seasonality_array = np.array(cfg.weekly_seasonality, dtype=np.float64)
    day_seasonality = seasonality_array[day_of_weeks]
    expected_demand = np.maximum(
        0.0,
        (cfg.base_demand + cfg.trend_slope * time_indices) * day_seasonality,
    )

    # 3. Discrete stochastic sampling
    if cfg.noise_family == "poisson":
        observed_requests = rng.poisson(lam=expected_demand).astype(np.int64)
    elif cfg.noise_family == "negative_binomial":
        # Negative Binomial parameterization:
        # Var = mu + alpha * mu^2
        # r = 1 / alpha
        # p = 1 / (1 + alpha * mu)
        r = 1.0 / cfg.noise_dispersion
        observed_requests = np.zeros(cfg.n_days, dtype=np.int64)
        for i, mu in enumerate(expected_demand):
            if mu <= 0.0:
                observed_requests[i] = 0
            else:
                p = 1.0 / (1.0 + cfg.noise_dispersion * mu)
                observed_requests[i] = rng.negative_binomial(n=r, p=p)
    elif cfg.noise_family == "fixed":
        observed_requests = np.round(expected_demand).astype(np.int64)
    else:
        raise ValueError(f"Unknown noise_family: {cfg.noise_family}")

    # Ensure non-negative integers
    observed_requests = np.maximum(0, observed_requests)

    return pd.DataFrame(
        {
            "date": dates,
            "time_index": time_indices,
            "day_of_week": day_of_weeks,
            "day_name": day_names,
            "is_weekend": is_weekends,
            "requests": observed_requests,
        }
    )
